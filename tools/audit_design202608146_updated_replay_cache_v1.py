def assert_snapshot_unchanged(snapshot: Mapping[str, Any]) -> None:
    held = os.fstat(int(snapshot["fd"]))
    path = Path(snapshot["path"])
    visible = os.lstat(path)
    identity = (
        int(snapshot["device"]),
        int(snapshot["inode"]),
        int(snapshot["size"]),
        int(snapshot["mtime_ns"]),
        int(snapshot["mode"]),
        int(snapshot["nlink"]),
    )
    held_identity = (
        held.st_dev,
        held.st_ino,
        held.st_size,
        held.st_mtime_ns,
        stat.S_IMODE(held.st_mode),
        held.st_nlink,
    )
    visible_identity = (
        visible.st_dev,
        visible.st_ino,
        visible.st_size,
        visible.st_mtime_ns,
        stat.S_IMODE(visible.st_mode),
        visible.st_nlink,
    )
    if identity != held_identity or identity != visible_identity:
        raise ProtocolError(f"held input identity changed: {snapshot['label']}")
    if sha256_fd(int(snapshot["fd"])) != snapshot["sha256"]:
        raise ProtocolError(f"held input bytes changed: {snapshot['label']}")
    flags = os.O_RDONLY | os.O_CLOEXEC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    visible_fd = os.open(path, flags)
    try:
        fcntl.flock(visible_fd, fcntl.LOCK_SH | fcntl.LOCK_NB)
        reopened = os.fstat(visible_fd)
        reopened_identity = (
            reopened.st_dev,
            reopened.st_ino,
            reopened.st_size,
            reopened.st_mtime_ns,
            stat.S_IMODE(reopened.st_mode),
            reopened.st_nlink,
        )
        if reopened_identity != identity:
            raise ProtocolError(
                f"visible input changed while reopening: {snapshot['label']}"
            )
        if sha256_fd(visible_fd) != snapshot["sha256"]:
            raise ProtocolError(f"visible input bytes changed: {snapshot['label']}")
    finally:
        try:
            fcntl.flock(visible_fd, fcntl.LOCK_UN)
        finally:
            os.close(visible_fd)


def release_snapshots(snapshots: Mapping[str, Mapping[str, Any]]) -> None:
    for snapshot in reversed(list(snapshots.values())):
        fd = int(snapshot["fd"])
        try:
            fcntl.flock(fd, fcntl.LOCK_UN)
        finally:
            os.close(fd)


def binding(path: Path, digest: str, mode: int) -> dict[str, Any]:
    observed = os.lstat(path)
    if (
        not stat.S_ISREG(observed.st_mode)
        or stat.S_IMODE(observed.st_mode) != mode
        or observed.st_nlink != 1
    ):
        raise ProtocolError(f"protocol binding stat drift: {relative(path)}")
    return {
        "path": relative(path),
        "sha256": digest,
        "mode_octal": f"{mode:04o}",
        "bytes": int(observed.st_size),
        "device": int(observed.st_dev),
        "inode": int(observed.st_ino),
        "mtime_ns": int(observed.st_mtime_ns),
        "nlink": int(observed.st_nlink),
    }


