def install_runtime_tripwires(torch: Any, stack: Mapping[str, Any]) -> dict[str, Any]:
    counters = {
        "checkpoint_load": 0,
        "checkpoint_save": 0,
        "model_init": 0,
        "model_forward": 0,
        "optimizer_init": 0,
        "optimizer_step": 0,
        "backward": 0,
        "cuda_lazy_init": 0,
        "bc_replay_update": 0,
    }
    originals: list[tuple[Any, str, Any]] = []

    def replace(target: Any, attribute: str, counter: str) -> None:
        if not hasattr(target, attribute):
            raise ProtocolError(f"runtime tripwire target absent: {attribute}")
        original = getattr(target, attribute)

        def denied(*positional: Any, **keyword: Any) -> Any:
            del positional, keyword
            counters[counter] += 1
            raise ProtocolError(f"forbidden zero-step operation attempted: {counter}")

        originals.append((target, attribute, original))
        setattr(target, attribute, denied)

    ppo = stack["ppo"]
    bc = stack["bc"]
    replace(torch, "load", "checkpoint_load")
    replace(torch, "save", "checkpoint_save")
    replace(torch.optim.Optimizer, "__init__", "optimizer_init")
    replace(torch.optim.Optimizer, "step", "optimizer_step")
    replace(torch.autograd, "backward", "backward")
    replace(torch.cuda, "_lazy_init", "cuda_lazy_init")
    replace(bc.EntityOptionPolicy, "__init__", "model_init")
    replace(bc.EntityOptionPolicy, "forward", "model_forward")
    replace(ppo, "model_forward", "model_forward")
    replace(ppo, "instantiate_model_from_bc", "model_init")
    replace(ppo, "instantiate_model_from_checkpoint", "model_init")
    replace(ppo, "bc_replay_update", "bc_replay_update")
    replace(ppo, "save_ppo_checkpoint", "checkpoint_save")
    return {"counters": counters, "originals": originals}


def restore_runtime_tripwires(state: Mapping[str, Any]) -> dict[str, int]:
    for target, attribute, original in reversed(list(state["originals"])):
        setattr(target, attribute, original)
    return {key: int(value) for key, value in state["counters"].items()}


def run_cache_profile(
    snapshots: Mapping[str, Mapping[str, Any]],
) -> dict[str, Any]:
    # This occurs after the immutable attempt marker.  No third-party module is
    # imported before this point.  Hiding every CUDA device before importing
    # torch ensures the cache-only process cannot acquire a CUDA device.
    os.environ["CUDA_VISIBLE_DEVICES"] = ""
    os.environ["CUBLAS_WORKSPACE_CONFIG"] = ":4096:8"
    torch = __import__("torch")
    orjson = __import__("orjson")
    numpy = __import__("numpy")
    if str(torch.__version__) != EXPECTED_TORCH_VERSION:
        raise ProtocolError(f"torch version drift: {torch.__version__}")
    if str(orjson.__version__) != EXPECTED_ORJSON_VERSION:
        raise ProtocolError(f"orjson version drift: {orjson.__version__}")
    if str(numpy.__version__) != EXPECTED_NUMPY_VERSION:
        raise ProtocolError(f"numpy version drift: {numpy.__version__}")
    if sys.byteorder != "little":
        raise ProtocolError(f"byte order drift: {sys.byteorder}")
    if bool(torch.cuda.is_initialized()):
        raise ProtocolError("CUDA was initialized before cache construction")

    stack: dict[str, Any] = {}
    closure: dict[str, Any] = {}
    cleanup: dict[str, Any] | None = None
    tripwires: dict[str, Any] | None = None
    try:
        stack, closure = load_authenticated_stack(snapshots)
        ppo = stack["ppo"]
        helper = stack["helper"]
        tripwires = install_runtime_tripwires(torch, stack)

        frozen_run_config = strict_json_bytes(
            read_fd_bytes(int(snapshots["guarded_u468_run_config"]["fd"])),
            "guarded U468 run_config",
        )
        config, model_config, parent_audit = validate_parent_and_clone_config(
            frozen_run_config, ppo
        )

        # The semantic clone is frozen against the repository archive path.
        # The actual cache read is transported through the already-held archive
        # descriptor so the mutable mode-0664 pathname cannot be swapped or
        # modified between authentication and DataLoader worker opens.
        archive_snapshot = snapshots["updated_general_replay"]
        archive_transport_path = f"/proc/self/fd/{int(archive_snapshot['fd'])}"
        transport_stat = os.stat(archive_transport_path)
        if (
            transport_stat.st_dev != int(archive_snapshot["device"])
            or transport_stat.st_ino != int(archive_snapshot["inode"])
            or transport_stat.st_size != int(archive_snapshot["size"])
        ):
            raise ProtocolError("held archive /proc descriptor identity drift")
        transport_config = copy.deepcopy(config)
        transport_config.bc_replay_data = archive_transport_path

        archive_manifest = archive_train_manifest(
            int(snapshots["updated_general_replay"]["fd"]),
            str(snapshots["updated_general_replay"]["sha256"]),
        )
        train_names = [entry["name"] for entry in archive_manifest["entries"]]
        train_index = {name: index for index, name in enumerate(train_names)}
        if len(train_index) != 70:
            raise ProtocolError("train member manifest identity collision")

        context = multiprocessing.get_context()
        start_method = context.get_start_method()
        if start_method != "fork":
            raise ProtocolError(
                f"cache profiler requires inherited fork guards, got {start_method}"
            )
        opened_bits = context.Array("b", len(train_names), lock=True)
        opened_calls = context.Value("Q", 0, lock=True)
        original_zip_open = zipfile.ZipFile.open
        original_loader = ppo.DataLoader
        loader_audits: list[dict[str, Any]] = []
        loader_proxies: list[Any] = []

        class GuardedLoaderProxy:
            def __init__(self, loader: Any) -> None:
                self.loader = loader
                self.iterator: Any | None = None
                self.explicit_shutdown_called = False
                self.workers: list[Any] = []
                self.worker_pids: list[int] = []
                self.worker_exitcodes_after_shutdown: dict[int, int] = {}
                self.workers_alive_after_shutdown: list[int] = []

            def __iter__(self) -> Any:
                if self.iterator is not None:
                    raise ProtocolError("guarded DataLoader iterated more than once")
                self.iterator = iter(self.loader)
                workers = list(getattr(self.iterator, "_workers", ()))
                self.workers = workers
                self.worker_pids = [
                    int(worker.pid) for worker in workers if worker.pid is not None
                ]
                if len(self.worker_pids) != 8 or len(set(self.worker_pids)) != 8:
                    raise ProtocolError("DataLoader did not start 8 distinct workers")
                return self.iterator

            def shutdown_workers(self) -> None:
                if self.iterator is None:
                    return
                shutdown = getattr(self.iterator, "_shutdown_workers", None)
                if not callable(shutdown):
                    raise ProtocolError("DataLoader iterator lacks explicit shutdown hook")
                shutdown()
                self.explicit_shutdown_called = True
                self.workers_alive_after_shutdown = [
                    int(worker.pid)
                    for worker in self.workers
                    if worker.pid is not None and worker.is_alive()
                ]
                if self.workers_alive_after_shutdown:
                    raise ProtocolError("DataLoader workers remained alive after shutdown")
                if any(worker.pid is None or worker.exitcode is None for worker in self.workers):
                    raise ProtocolError("DataLoader worker exit code unavailable")
                self.worker_exitcodes_after_shutdown = {
                    int(worker.pid): int(worker.exitcode) for worker in self.workers
                }
                if any(
                    exitcode != 0
                    for exitcode in self.worker_exitcodes_after_shutdown.values()
                ):
                    raise ProtocolError("DataLoader worker exited nonzero")

        def guarded_zip_open(
            archive: zipfile.ZipFile,
            name: Any,
            mode: str = "r",
            *positional: Any,
            **keyword: Any,
        ) -> Any:
            member = name.filename if isinstance(name, zipfile.ZipInfo) else str(name)
            if mode != "r" or not member.startswith(TRAIN_PREFIX):
                raise ProtocolError("cache builder attempted non-train ZIP member access")
            if member not in train_index:
                raise ProtocolError("cache builder attempted unmanifested train member")
            with opened_calls.get_lock():
                opened_calls.value += 1
            with opened_bits.get_lock():
                opened_bits[train_index[member]] = 1
            return original_zip_open(archive, name, mode, *positional, **keyword)

        def guarded_loader(*positional: Any, **keyword: Any) -> Any:
            dataset = positional[0] if positional else keyword.get("dataset")
            observed = {
                "num_workers": int(keyword.get("num_workers", -1)),
                "batch_size": int(keyword.get("batch_size", -1)),
                "dataset_type": type(dataset).__name__,
                "archive_path": str(getattr(dataset, "archive_path", "")),
                "split": getattr(dataset, "split", None),
                "max_rows": getattr(dataset, "max_rows", None),
                "split_seed": getattr(dataset, "split_seed", None),
                "shuffle_seed": getattr(dataset, "shuffle_seed", None),
                "epoch": getattr(dataset, "epoch", None),
                "split_mode": getattr(dataset, "split_mode", None),
                "shuffle_buffer_rows": getattr(dataset, "shuffle_buffer_rows", None),
                "use_trajectory_weights": getattr(
                    dataset, "use_trajectory_weights", None
                ),
            }
            expected = {
                "num_workers": 8,
                "batch_size": 256,
                "dataset_type": "ZipDecisionDataset",
                "archive_path": archive_transport_path,
                "split": "train",
                "max_rows": 18432,
                "split_seed": 202608145,
                "shuffle_seed": 202608186,
                "epoch": 0,
                "split_mode": "archive",
                "shuffle_buffer_rows": 0,
                "use_trajectory_weights": False,
            }
            observed["exact"] = all(
                observed.get(key) == value for key, value in expected.items()
            )
            if observed["exact"] is not True:
                raise ProtocolError(f"DataLoader/cache dataset contract drift: {observed}")
            loader_audits.append(observed)
            proxy = GuardedLoaderProxy(original_loader(*positional, **keyword))
            loader_proxies.append(proxy)
            return proxy

        zipfile.ZipFile.open = guarded_zip_open
        ppo.DataLoader = guarded_loader
        try:
            replay_batches = ppo.build_bc_replay_batches(
                transport_config, model_config
            )
        finally:
            try:
                for proxy in loader_proxies:
                    proxy.shutdown_workers()
            finally:
                ppo.DataLoader = original_loader
                zipfile.ZipFile.open = original_zip_open

        if len(loader_audits) != 1 or loader_audits[0].get("exact") is not True:
            raise ProtocolError("cache builder did not create exactly one guarded loader")
        if (
            len(loader_proxies) != 1
            or loader_proxies[0].iterator is None
            or loader_proxies[0].explicit_shutdown_called is not True
            or loader_proxies[0].workers_alive_after_shutdown
            or len(loader_proxies[0].worker_pids) != 8
            or len(set(loader_proxies[0].worker_pids)) != 8
            or len(loader_proxies[0].worker_exitcodes_after_shutdown) != 8
            or any(
                exitcode != 0
                for exitcode in loader_proxies[0].worker_exitcodes_after_shutdown.values()
            )
        ):
            raise ProtocolError("DataLoader worker lifecycle audit failed")
        loader_audits[0]["worker_pids_started_count"] = len(
            loader_proxies[0].worker_pids
        )
        loader_audits[0]["worker_pids_distinct"] = True
        loader_audits[0]["worker_exitcodes_after_shutdown"] = {
            str(pid): exitcode
            for pid, exitcode in sorted(
                loader_proxies[0].worker_exitcodes_after_shutdown.items()
            )
        }
        loader_audits[0]["explicit_worker_shutdown_called"] = True
        loader_audits[0]["workers_alive_after_shutdown"] = 0
        if len(replay_batches) != 72:
            raise ProtocolError("cache builder did not produce exactly 72 batches")

        aggregate_sha256, batch_sha256 = helper.replay_cache_manifest(replay_batches)
        if len(batch_sha256) != 72 or any(not HEX64.fullmatch(x) for x in batch_sha256):
            raise ProtocolError("cache hash helper returned malformed batch hashes")
        independent_aggregate_sha256 = aggregate_batch_sha256(batch_sha256)
        if independent_aggregate_sha256 != aggregate_sha256:
            raise ProtocolError("cache aggregate hash independent reconstruction drift")
        per_batch_rows = [
            int(batch["action_counts"].shape[0]) for batch in replay_batches
        ]
        per_batch_context34 = [
            int((batch["contexts"] == ppo.SKILL_ORDER_CONTEXT).sum())
            for batch in replay_batches
        ]
        if per_batch_rows != [256] * 72:
            raise ProtocolError("cache contains a short or oversized batch")
        if per_batch_context34 != [4] * 72:
            raise ProtocolError("cache context34 stratification drift")
        expected_tensor_keys = {
            "global_fields",
            "global_field_mask",
            "global_numeric",
            "state_fields",
            "state_field_mask",
            "state_numeric",
            "state_mask",
            "option_fields",
            "option_field_mask",
            "option_numeric",
            "option_mask",
            "targets",
            "action_counts",
            "action_sequences",
            "min_counts",
            "max_counts",
            "contexts",
            "sample_weights",
            "win_targets",
        }
        if any(set(batch) != expected_tensor_keys for batch in replay_batches):
            raise ProtocolError("cache tensor key set drift")
        if not all(
            isinstance(value, torch.Tensor)
            for batch in replay_batches
            for value in batch.values()
        ):
            raise ProtocolError("cache contains a non-tensor value")
        all_tensors_cpu_no_grad = all(
            value.device.type == "cpu" and value.requires_grad is False
            for batch in replay_batches
            for value in batch.values()
        )
        if not all_tensors_cpu_no_grad:
            raise ProtocolError("cache tensor escaped CPU or requires gradients")
        if not all(
            bool(torch.isfinite(value).all())
            for batch in replay_batches
            for value in batch.values()
            if value.is_floating_point()
        ):
            raise ProtocolError("cache contains non-finite floating tensors")

        selected_sha256 = [batch_sha256[index] for index in SELECTED_BATCH_INDICES]
        opened_indices = [
            index for index, value in enumerate(list(opened_bits)) if int(value) == 1
        ]
        if int(opened_calls.value) <= 0 or not opened_indices:
            raise ProtocolError("guarded cache builder recorded no train member reads")
        terminal_repo_modules = repo_modules()
        unexpected_runtime_repo_modules = {
            name: path
            for name, path in terminal_repo_modules.items()
            if name not in closure["repo_before"]
            and closure["permitted_repo_modules"].get(name) != path
        }
        if unexpected_runtime_repo_modules:
            raise ProtocolError(
                "cache runtime lazily loaded unbound repository module"
            )
        if sys.path != list(closure["path_before"]):
            raise ProtocolError("cache runtime changed sys.path after held load")
        closure["checks"]["no_unbound_repository_lazy_load_during_cache"] = True
        closure["checks"]["sys_path_unchanged_during_cache"] = True
        closure["unexpected_repo_modules_terminal"] = unexpected_runtime_repo_modules
        tripwire_counters = {
            key: int(value) for key, value in tripwires["counters"].items()
        }
        if any(tripwire_counters.values()):
            raise ProtocolError("zero-step runtime tripwire counter is nonzero")
        cuda_initialized_terminal = bool(torch.cuda.is_initialized())
        if cuda_initialized_terminal:
            raise ProtocolError("CUDA initialized during cache construction")

        output = {
            "runtime": {
                "python": str(EXPECTED_PYTHON),
                "python_version": sys.version.split()[0],
                "torch_version": str(torch.__version__),
                "orjson_version": str(orjson.__version__),
                "numpy_version": str(numpy.__version__),
                "byteorder": sys.byteorder,
                "CUDA_VISIBLE_DEVICES": os.environ.get("CUDA_VISIBLE_DEVICES"),
                "cuda_state_queries_by_runner": 2,
                "cuda_is_initialized_terminal": cuda_initialized_terminal,
                "cuda_devices_acquired": 0,
                "multiprocessing_start_method": start_method,
            },
            "zero_step_runtime_tripwires": {
                "armed_before_cache_construction": True,
                "counters": tripwire_counters,
                "all_counters_zero": not any(tripwire_counters.values()),
            },
            "authenticated_implementation_closure": {
                key: value
                for key, value in closure.items()
                if key
                not in {"path_before", "repo_before", "permitted_repo_modules"}
            },
            "parent_and_clone_audit": parent_audit,
            "held_archive_transport": {
                "semantic_config_path": str(UPDATED_REPLAY),
                "runtime_transport": "/proc/self/fd/<held_archive_fd>",
                "transport_targets_exact_held_device_inode_size": True,
                "path_based_mode0664_TOCTOU_closed": True,
                "DataLoader_workers_inherit_guard_and_held_fd": True,
            },
            "archive_train_member_manifest": archive_manifest,
            "guarded_member_access": {
                "ZipFile_open_rejected_every_non_train_or_unmanifested_member": True,
                "train_member_open_calls": int(opened_calls.value),
                "opened_train_member_indices": opened_indices,
                "opened_train_member_names": [train_names[index] for index in opened_indices],
                "non_train_member_payloads_opened": 0,
            },
            "loader_audit": loader_audits[0],
            "cache": {
                "aggregate_cache_sha256": aggregate_sha256,
                "independently_recomputed_aggregate_cache_sha256": (
                    independent_aggregate_sha256
                ),
                "all_72_batch_sha256_in_index_order": batch_sha256,
                "selected_G8_batch_indices": list(SELECTED_BATCH_INDICES),
                "selected_8_batch_sha256_in_frozen_index_order": selected_sha256,
                "per_batch_row_count": per_batch_rows,
                "per_batch_context34_count": per_batch_context34,
                "rows_total": sum(per_batch_rows),
                "context34_rows_total": sum(per_batch_context34),
                "archive_train_member_manifest_sha256": archive_manifest["sha256"],
            },
            "integrity": {
                "batches_exact72": len(replay_batches) == 72,
                "rows_exact72x256": sum(per_batch_rows) == 18432,
                "every_batch_rows_exact256": per_batch_rows == [256] * 72,
                "every_batch_context34_exact4": per_batch_context34 == [4] * 72,
                "context34_total_exact288": sum(per_batch_context34) == 288,
                "selected_indices_exact_and_distinct": (
                    tuple(SELECTED_BATCH_INDICES) == (1, 3, 4, 5, 6, 7, 8, 11)
                    and len(set(SELECTED_BATCH_INDICES)) == 8
                ),
                "all_hashes_well_formed": HEX64.fullmatch(aggregate_sha256)
                is not None
                and all(HEX64.fullmatch(value) for value in batch_sha256),
                "aggregate_hash_independently_recomputed": (
                    independent_aggregate_sha256 == aggregate_sha256
                ),
                "all_cache_floats_finite": True,
                "all_cache_tensors_CPU_and_no_grad": all_tensors_cpu_no_grad,
                "cuda_never_initialized": not cuda_initialized_terminal,
                "zero_step_tripwires_all_zero": not any(
                    tripwire_counters.values()
                ),
                "parent_checkpoint_never_deserialized": True,
                "parent_checkpoint_held_file_unchanged_until_terminal_recheck": True,
                "engine_accesses_zero": EngineSentinel.accesses == 0,
            },
            "scope_audit": {
                "optimizer_instances": 0,
                "optimizer_steps": 0,
                "model_instances": 0,
                "model_forwards": 0,
                "backward_calls": 0,
                "checkpoint_writes": 0,
                "changed_candidates_constructed_or_evaluated": 0,
                "identity_manifest_constructed": False,
                "validation_test_gold_payload_or_score_rows_opened": 0,
                "network": False,
                "package_upload_submission": False,
            },
        }
        if not all(output["integrity"].values()):
            raise ProtocolError("terminal cache integrity gate failed")
        return output
    finally:
        try:
            if tripwires is not None:
                restore_runtime_tripwires(tripwires)
        finally:
            if stack and closure:
                cleanup = cleanup_authenticated_stack(stack, closure)
        if cleanup is not None and not all(
            value for key, value in cleanup.items() if key != "remaining_private_repo_modules"
        ):
            raise ProtocolError(f"authenticated module cleanup failed: {cleanup}")


