def main() -> int:
    args = parse_args()
    runtime = validate_runtime_and_argv(args)
    root_directory = open_locked_directory(
        "repository_root", ROOT, PUBLICATION_DIRECTORY_BINDINGS["repository_root"]
    )
    try:
        artifacts_directory = open_locked_directory(
            "artifacts",
            ROOT / "artifacts",
            PUBLICATION_DIRECTORY_BINDINGS["artifacts"],
        )
    except BaseException:
        release_directory(root_directory)
        raise
    root_fd = int(root_directory["fd"])
    artifacts_fd = int(artifacts_directory["fd"])
    snapshots: dict[str, dict[str, Any]] = {}
    attempt_evidence: dict[str, Any] | None = None
    phase = "pre_attempt_control_plane"
    try:
        if not target_absent(root_fd, ATTEMPT.name):
            raise FileExistsError(f"attempt target already exists: {relative(ATTEMPT)}")
        if not target_absent(artifacts_fd, RESULT.name):
            raise FileExistsError(f"result target already exists: {relative(RESULT)}")

        snapshots["runner"] = open_locked_input("runner", SCRIPT, None, 0o555)
        snapshots["protocol"] = open_locked_input(
            "execution_protocol", PROTOCOL, args.expected_protocol_sha256, 0o444
        )
        for label, (path, digest, mode) in STATIC_BINDINGS.items():
            snapshots[label] = open_locked_input(label, path, digest, mode)

        runner_source = read_fd_bytes(int(snapshots["runner"]["fd"]))
        static_audit = static_source_audit(runner_source)
        master = strict_json_bytes(
            read_fd_bytes(int(snapshots["master"]["fd"])), "cache profile master"
        )
        protocol = strict_json_bytes(
            read_fd_bytes(int(snapshots["protocol"]["fd"])),
            "cache profile execution protocol",
        )
        lineage_audit = validate_master_and_lineage(master, snapshots)
        protocol_audit = validate_protocol(protocol, snapshots["runner"]["sha256"])
        for snapshot in snapshots.values():
            assert_snapshot_unchanged(snapshot)

        # Recheck a common absent-target instant immediately before the atomic
        # attempt claim.  The O_EXCL open remains the authoritative race gate.
        if not (
            target_absent(root_fd, ATTEMPT.name)
            and target_absent(artifacts_fd, RESULT.name)
        ):
            raise FileExistsError("publication target appeared before attempt claim")
        attempt_payload = {
            "schema_version": f"{SCHEMA}-attempt-v1",
            "status": "CACHE_PROFILE_ATTEMPT_CONSUMED_BEFORE_ANY_THIRD_PARTY_OR_REPO_IMPORT",
            "branch": BRANCH,
            "attempt": 1,
            "attempts_authorized": 1,
            "started_at_utc": utc_now(),
            "runner_sha256": snapshots["runner"]["sha256"],
            "protocol_sha256": snapshots["protocol"]["sha256"],
            "master_sha256": snapshots["master"]["sha256"],
            "input_sha256": {
                label: snapshot["sha256"]
                for label, snapshot in snapshots.items()
                if label not in {"runner", "protocol"}
            },
            "runtime": runtime,
            "static_source_audit": static_audit,
            "master_and_lineage_audit": lineage_audit,
            "protocol_audit": protocol_audit,
            "targets_absent_at_claim": {
                "attempt": True,
                "result": True,
            },
            "publication_directories_held_from_absence_check": {
                "repository_root": directory_evidence(root_directory),
                "artifacts": directory_evidence(artifacts_directory),
            },
            "runner_held_identity_at_claim": public_evidence(snapshots["runner"]),
            "third_party_or_repository_modules_imported_before_claim": 0,
            "optimizer_steps": 0,
            "changed_candidates_constructed_or_evaluated": 0,
            "retry_authorized": False,
        }
        attempt_evidence = publish_exclusive(
            root_fd, ATTEMPT.name, attempt_payload, ATTEMPT
        )

        phase = "post_attempt_authenticated_cache_construction"
        profile = run_cache_profile(snapshots)
        phase = "post_cache_input_identity_recheck"
        for snapshot in snapshots.values():
            assert_snapshot_unchanged(snapshot)
        assert_directory_unchanged(root_directory)
        assert_directory_unchanged(artifacts_directory)
        phase = "success_result_publication"
        result = {
            "schema_version": SCHEMA,
            "status": "CACHE_PROFILE_COMPLETED_ZERO_STEP_TRAIN_ONLY",
            "branch": BRANCH,
            "completed_at_utc": utc_now(),
            "attempt": attempt_evidence,
            "protocol": public_evidence(snapshots["protocol"]),
            "runner": public_evidence(snapshots["runner"]),
            "master": public_evidence(snapshots["master"]),
            "bindings": {
                label: public_evidence(snapshot)
                for label, snapshot in snapshots.items()
                if label not in {"runner", "protocol", "master"}
            },
            "static_source_audit": static_audit,
            "master_and_lineage_audit": lineage_audit,
            "protocol_audit": protocol_audit,
            **profile,
            "terminal_decision": {
                "cache_profile_GO_for_separate_G8_freeze": True,
                "this_result_does_not_authorize_G8_execution": True,
                "retry_authorized": False,
                "candidate_consumed": 0,
            },
        }
        result_evidence = publish_exclusive(
            artifacts_fd, RESULT.name, result, RESULT
        )
        print(
            json.dumps(
                {
                    "status": result["status"],
                    "result": result_evidence,
                    "aggregate_cache_sha256": result["cache"][
                        "aggregate_cache_sha256"
                    ],
                    "optimizer_steps": 0,
                    "candidate_consumed": 0,
                },
                ensure_ascii=False,
                sort_keys=True,
            )
        )
        return 0
    except BaseException as error:
        if attempt_evidence is None:
            raise
        unchanged = True
        try:
            for snapshot in snapshots.values():
                assert_snapshot_unchanged(snapshot)
            assert_directory_unchanged(root_directory)
            assert_directory_unchanged(artifacts_directory)
        except BaseException:
            unchanged = False
        failure = sanitized_failure(
            error,
            phase,
            attempt_evidence,
            snapshots["protocol"]["sha256"],
            snapshots["runner"]["sha256"],
            unchanged,
        )
        publish_exclusive(artifacts_fd, RESULT.name, failure, RESULT)
        print(
            json.dumps(
                {
                    "status": failure["status"],
                    "phase": phase,
                    "retry_authorized": False,
                    "raw_error_published": False,
                },
                sort_keys=True,
            ),
            file=sys.stderr,
        )
        return 1
    finally:
        if snapshots:
            release_snapshots(snapshots)
        release_directory(artifacts_directory)
        release_directory(root_directory)


if __name__ == "__main__":
    raise SystemExit(main())
