def strict_json_bytes(payload: bytes, label: str) -> dict[str, Any]:
    def reject_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in pairs:
            if key in result:
                raise ProtocolError(f"{label} has duplicate JSON key {key!r}")
            result[key] = value
        return result

    try:
        value = json.loads(payload, object_pairs_hook=reject_duplicates)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ProtocolError(f"{label} is not strict UTF-8 JSON") from error
    if not isinstance(value, dict):
        raise ProtocolError(f"{label} root must be an object")
    return value


def sha256_fd(fd: int) -> str:
    observed = os.fstat(fd)
    digest = hashlib.sha256()
    offset = 0
    while offset < observed.st_size:
        chunk = os.pread(fd, min(1024 * 1024, observed.st_size - offset), offset)
        if not chunk:
            raise ProtocolError("short read while hashing held input")
        digest.update(chunk)
        offset += len(chunk)
    if offset != observed.st_size:
        raise ProtocolError("held input size changed while hashing")
    return digest.hexdigest()


def read_fd_bytes(fd: int) -> bytes:
    observed = os.fstat(fd)
    chunks: list[bytes] = []
    offset = 0
    while offset < observed.st_size:
        chunk = os.pread(fd, min(1024 * 1024, observed.st_size - offset), offset)
        if not chunk:
            raise ProtocolError("short read from held input")
        chunks.append(chunk)
        offset += len(chunk)
    result = b"".join(chunks)
    if len(result) != observed.st_size:
        raise ProtocolError("held input byte count drift")
    return result


def open_locked_input(
    label: str,
    path: Path,
    expected_sha256: str | None,
    expected_mode: int,
) -> dict[str, Any]:
    flags = os.O_RDONLY | os.O_CLOEXEC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fd = os.open(path, flags)
    try:
        fcntl.flock(fd, fcntl.LOCK_SH | fcntl.LOCK_NB)
        observed = os.fstat(fd)
        if not stat.S_ISREG(observed.st_mode):
            raise ProtocolError(f"{label} must be a regular file")
        if observed.st_nlink != 1:
            raise ProtocolError(f"{label} must have exactly one hard link")
        mode = stat.S_IMODE(observed.st_mode)
        if mode != expected_mode:
            raise ProtocolError(
                f"{label} mode drift: expected {expected_mode:04o}, got {mode:04o}"
            )
        digest = sha256_fd(fd)
        if expected_sha256 is not None and digest != expected_sha256:
            raise ProtocolError(f"{label} SHA-256 drift")
        return {
            "label": label,
            "path": path,
            "fd": fd,
            "sha256": digest,
            "mode": mode,
            "device": observed.st_dev,
            "inode": observed.st_ino,
            "size": observed.st_size,
            "mtime_ns": observed.st_mtime_ns,
            "nlink": observed.st_nlink,
        }
    except BaseException:
        os.close(fd)
        raise


