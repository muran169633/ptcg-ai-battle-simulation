def publish_exclusive(
    directory_fd: int,
    leaf: str,
    payload: Mapping[str, Any],
    relative_path: Path,
) -> dict[str, Any]:
    if Path(leaf).name != leaf or leaf in {"", ".", ".."}:
        raise ProtocolError("publication leaf is invalid")
    raw = canonical_json_bytes(payload)
    flags = os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_CLOEXEC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fd = os.open(leaf, flags, 0o600, dir_fd=directory_fd)
    try:
        offset = 0
        while offset < len(raw):
            written = os.write(fd, raw[offset:])
            if written <= 0:
                raise ProtocolError("short exclusive publication write")
            offset += written
        os.fsync(fd)
        os.fchmod(fd, 0o444)
        os.fsync(fd)
        observed = os.fstat(fd)
        if (
            not stat.S_ISREG(observed.st_mode)
            or stat.S_IMODE(observed.st_mode) != 0o444
            or observed.st_nlink != 1
            or observed.st_size != len(raw)
        ):
            raise ProtocolError("immutable publication shape drift")
        if sha256_fd(fd) != sha256_bytes(raw):
            raise ProtocolError("immutable publication held-fd readback drift")
        os.fsync(directory_fd)
    finally:
        os.close(fd)
    return {
        "path": relative(relative_path),
        "sha256": sha256_bytes(raw),
        "mode_octal": "0444",
        "bytes": len(raw),
    }


def dotted_name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        parent = dotted_name(node.value)
        return f"{parent}.{node.attr}" if parent else node.attr
    return None


def static_source_audit(source: bytes) -> dict[str, Any]:
    tree = ast.parse(source, filename=str(SCRIPT))
    imports: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imports.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imports.add(node.module.split(".")[0])
    forbidden_imports = {
        "torch",
        "orjson",
        "train_ppo",
        "train_bc_orbit",
        "run_ppo_bc_repair",
        "subprocess",
        "socket",
        "requests",
        "urllib",
        "http",
        "ftplib",
    }
    bad_imports = sorted(imports & forbidden_imports)
    call_names = {
        name
        for node in ast.walk(tree)
        if isinstance(node, ast.Call)
        for name in [dotted_name(node.func)]
        if name is not None
    }
    forbidden_calls = sorted(
        name
        for name in call_names
        if name in {
            "subprocess.run",
            "subprocess.Popen",
            "torch.cuda.is_available",
            "torch.cuda.manual_seed_all",
            "torch.optim.AdamW",
            "torch.load",
        }
        or name.endswith(".backward")
        or name.endswith(".model_forward")
        or "instantiate_model" in name
    )
    required_functions = {
        "expected_protocol",
        "validate_master_and_lineage",
        "validate_protocol",
        "run_cache_profile",
        "publish_exclusive",
        "sanitized_failure",
        "main",
    }
    observed_functions = {
        node.name for node in tree.body if isinstance(node, ast.FunctionDef)
    }
    main_guards = [
        node
        for node in tree.body
        if isinstance(node, ast.If)
        and isinstance(node.test, ast.Compare)
        and isinstance(node.test.left, ast.Name)
        and node.test.left.id == "__name__"
        and len(node.test.ops) == 1
        and isinstance(node.test.ops[0], ast.Eq)
        and len(node.test.comparators) == 1
        and isinstance(node.test.comparators[0], ast.Constant)
        and node.test.comparators[0].value == "__main__"
    ]
    checks = {
        "no_third_party_or_repo_static_imports": not bad_imports,
        "no_forbidden_training_cuda_or_network_calls": not forbidden_calls,
        "required_control_functions_present": required_functions <= observed_functions,
        "single_main_guard": len(main_guards) == 1,
    }
    if not all(checks.values()):
        raise ProtocolError(
            f"runner static source audit failed: imports={bad_imports}, "
            f"calls={forbidden_calls}, checks={checks}"
        )
    return {
        "checks": checks,
        "top_level_import_roots": sorted(imports),
        "forbidden_imports_observed": bad_imports,
        "forbidden_calls_observed": forbidden_calls,
    }


