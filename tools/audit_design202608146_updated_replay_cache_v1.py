def archive_train_manifest(archive_fd: int, archive_sha256: str) -> dict[str, Any]:
    duplicate = os.dup(archive_fd)
    try:
        with os.fdopen(duplicate, "rb", closefd=True) as handle:
            duplicate = -1
            with zipfile.ZipFile(handle) as archive:
                infos = archive.infolist()
    finally:
        if duplicate >= 0:
            os.close(duplicate)
    names = [info.filename for info in infos]
    if len(names) != len(set(names)):
        raise ProtocolError("updated replay ZIP has duplicate central-directory names")
    entries: list[dict[str, Any]] = []
    forbidden_member_count = 0
    for central_index, info in enumerate(infos):
        name = info.filename
        if name.startswith(FORBIDDEN_PREFIXES):
            forbidden_member_count += 1
        if not (name.startswith(TRAIN_PREFIX) and name.endswith(".jsonl")):
            continue
        pure = Path(name)
        if pure.is_absolute() or ".." in pure.parts or info.is_dir():
            raise ProtocolError("irregular train member path in updated replay ZIP")
        unix_mode = (int(info.external_attr) >> 16) & 0xFFFF
        if unix_mode and stat.S_ISLNK(unix_mode):
            raise ProtocolError("symlink train member in updated replay ZIP")
        entries.append(
            {
                "train_index": len(entries),
                "central_index": central_index,
                "name": name,
                "crc32_hex": f"{int(info.CRC):08x}",
                "compress_type": int(info.compress_type),
                "flag_bits": int(info.flag_bits),
                "compressed_bytes": int(info.compress_size),
                "uncompressed_bytes": int(info.file_size),
            }
        )
    if len(entries) != 70:
        raise ProtocolError(f"updated replay train shard count is {len(entries)}, not 70")
    expected_names = [f"train/part-{index:05d}.jsonl" for index in range(70)]
    if [entry["name"] for entry in entries] != expected_names:
        raise ProtocolError(
            "updated replay train members are not exact ordered part-00000..00069"
        )
    if any(int(entry["flag_bits"]) & 0x1 for entry in entries):
        raise ProtocolError("updated replay contains encrypted train member")
    core = {
        "schema_version": "ptcg-design202608146-train-zip-central-directory-v1",
        "archive_sha256": archive_sha256,
        "selector": "central-directory order where name starts train/ and ends .jsonl",
        "exact_expected_names": expected_names,
        "train_member_count": len(entries),
        "compressed_bytes_total": sum(
            int(entry["compressed_bytes"]) for entry in entries
        ),
        "uncompressed_bytes_total": sum(
            int(entry["uncompressed_bytes"]) for entry in entries
        ),
        "entries": entries,
    }
    manifest_sha256 = sha256_bytes(canonical_json_bytes(core))
    return {
        "definition": (
            "canonical JSON of train/*.jsonl central-directory entries in exact "
            "central-directory order, including train/central indices, name, "
            "CRC, flag bits, compression type, and compressed/uncompressed sizes"
        ),
        "sha256": manifest_sha256,
        "canonical_core": core,
        "train_member_count": len(entries),
        "forbidden_prefix_member_count_in_inventory_only": forbidden_member_count,
        "archive_member_payloads_opened_for_inventory": 0,
        "entries": entries,
    }


def exec_held_module(name: str, source: bytes, canonical_path: Path) -> types.ModuleType:
    module = types.ModuleType(name)
    module.__file__ = str(canonical_path)
    module.__cached__ = None
    module.__loader__ = None
    module.__package__ = None
    module.__spec__ = None
    sys.modules[name] = module
    try:
        exec(compile(source, str(canonical_path), "exec"), module.__dict__)
    except BaseException:
        sys.modules.pop(name, None)
        raise
    return module


def repo_modules() -> dict[str, str]:
    result: dict[str, str] = {}
    for name, module in list(sys.modules.items()):
        raw = getattr(module, "__file__", None)
        if not isinstance(raw, str):
            continue
        try:
            path = Path(raw).resolve()
            path.relative_to(ROOT)
        except (OSError, ValueError):
            continue
        result[name] = str(path)
    return result


