def open_locked_directory(
    label: str, path: Path, expected: Mapping[str, Any]
) -> dict[str, Any]:
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fd = os.open(path, flags)
    try:
        fcntl.flock(fd, fcntl.LOCK_SH | fcntl.LOCK_NB)
        held = os.fstat(fd)
        visible = os.lstat(path)
        if not stat.S_ISDIR(held.st_mode) or not stat.S_ISDIR(visible.st_mode):
            raise ProtocolError(f"{label} publication directory is not a directory")
        held_identity = (
            held.st_dev,
            held.st_ino,
            stat.S_IMODE(held.st_mode),
            held.st_nlink,
        )
        visible_identity = (
            visible.st_dev,
            visible.st_ino,
            stat.S_IMODE(visible.st_mode),
            visible.st_nlink,
        )
        expected_identity = (
            int(expected["device"]),
            int(expected["inode"]),
            int(expected["mode"]),
            int(expected["nlink"]),
        )
        if held_identity != expected_identity or visible_identity != expected_identity:
            raise ProtocolError(f"{label} publication directory identity drift")
        return {
            "label": label,
            "path": path,
            "fd": fd,
            "device": held.st_dev,
            "inode": held.st_ino,
            "mode": stat.S_IMODE(held.st_mode),
            "nlink": held.st_nlink,
        }
    except BaseException:
        os.close(fd)
        raise


